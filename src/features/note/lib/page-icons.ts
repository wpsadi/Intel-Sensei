const LUCIDE_PREFIX = 'lucide:'

export const lucideRef = (name: string) => `${LUCIDE_PREFIX}${name}`

/** The lucide icon a stored `lucide:Name` value points at, if any. */
export function lucideIcon(icon: string | undefined): LucideIcon | undefined {
  if (!icon?.startsWith(LUCIDE_PREFIX)) return undefined
  return PAGE_ICONS[icon.slice(LUCIDE_PREFIX.length)]
}
